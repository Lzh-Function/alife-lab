def make_synthetic_cns_embodied_pack() -> ConnectomePack:
    """Built-in 72-neuron offline Brain + VNC spiking CNS circuit for F8 Level 2 CPU CI & tests.

    Layout:
    - 0..23  : Brain reflex + descending circuit (identical to ``synthetic_fly_embodied``)
    - 24..29 : 6 VNC leg proprioceptors (``proprio_LF .. proprio_RH``)
    - 30..35 : 6 VNC premotor half-center interneurons (Tripod A {LF, RM, LH} vs B {RF, LM, RH})
    - 36..71 : 36 VNC antagonist leg motor neurons (6 legs x 6 muscle channels)

    Driven purely by spiking LIF dynamics (NO hand-crafted CPG): ``DNp09`` excites the VNC
    premotor half-centers which mutually inhibit anti-phase tripods and receive proprioceptive
    load feedback, directly firing the 36 antagonist leg motor neurons!
    """
    base = make_synthetic_fly_embodied_pack()
    bc = base.cells
    n_brain = bc.num_cells  # 24
    n_total = 72

    types = list(bc.cell_type)
    super_classes = list(bc.super_class)
    classes = list(bc.cell_class)
    sub_classes = list(bc.cell_sub_class)
    regions = list(bc.region)
    sides = list(bc.side)
    roles = list(bc.role.tolist())
    nts = list(bc.neurotransmitter)
    xyz = [bc.position_nm[i].tolist() for i in range(n_brain)]

    leg_y_nm = {
        "LF": -190000.0,
        "LM": -260000.0,
        "LH": -330000.0,
        "RF": -190000.0,
        "RM": -260000.0,
        "RH": -330000.0,
    }
    leg_x_nm = {
        "LF": -75000.0,
        "LM": -80000.0,
        "LH": -75000.0,
        "RF": 75000.0,
        "RM": 80000.0,
        "RH": 75000.0,
    }
    leg_side = {
        "LF": "left",
        "LM": "left",
        "LH": "left",
        "RF": "right",
        "RM": "right",
        "RH": "right",
    }
    leg_nm_name = {"LF": "T1", "LM": "T2", "LH": "T3", "RF": "T1", "RM": "T2", "RH": "T3"}

    io_ports = dict(base.io_ports)

    # 24..29: 6 leg proprioceptors
    for li, leg in enumerate(LEG_NAMES):
        idx = 24 + li
        types.append(f"FeCO_{leg}")
        super_classes.append("sensory")
        classes.append("chordotonal_organ_neuron")
        sub_classes.append("proprioceptor")
        regions.append(f"VNC_{leg_nm_name[leg]}")
        sides.append(leg_side[leg])
        roles.append(ROLE_SENSORY)
        nts.append("acetylcholine")
        xyz.append([leg_x_nm[leg] * 1.15, leg_y_nm[leg], -30000.0])
        io_ports[f"proprio_{leg}"] = IOPort(
            f"proprio_{leg}",
            "sensory",
            f"{leg} leg proprioceptor",
            f"Synthetic {leg} proprioceptive feedback neuron.",
            np.array([idx], dtype=np.int32),
            f"cell_type == 'FeCO_{leg}'",
        )

    # 30..35: 6 VNC premotor interneurons (inhibitory mutual half-centers + excitatory drive)
    for leg in LEG_NAMES:
        types.append(f"VNC_PM_{leg}")
        super_classes.append("ventral_nerve_cord_intrinsic")
        classes.append("single_leg_neuromere")
        sub_classes.append("premotor_cpg")
        regions.append(f"VNC_{leg_nm_name[leg]}")
        sides.append(leg_side[leg])
        roles.append(ROLE_INTERNEURON)
        nts.append("acetylcholine")
        xyz.append([leg_x_nm[leg] * 0.55, leg_y_nm[leg], 0.0])

    # 36..71: 36 leg motor neurons (6 legs x 6 antagonist muscle pools)
    for li, leg in enumerate(LEG_NAMES):
        for mi, mgrp in enumerate(MUSCLE_CHANNELS):
            idx = 36 + li * 6 + mi
            types.append(f"MN_{leg}_{mgrp}")
            super_classes.append("motor")
            classes.append("leg_motor")
            sub_classes.append(mgrp)
            regions.append(f"VNC_{leg_nm_name[leg]}")
            sides.append(leg_side[leg])
            roles.append(ROLE_MOTOR)
            nts.append("glutamate")
            xyz.append([leg_x_nm[leg] * 0.9, leg_y_nm[leg] + (mi - 2.5) * 9000.0, 25000.0])
            io_ports[f"mn_{leg}_{mgrp}"] = IOPort(
                f"mn_{leg}_{mgrp}",
                "motor",
                f"{leg} {mgrp} motor neuron",
                f"Synthetic {leg} {mgrp} leg motor neuron.",
                np.array([idx], dtype=np.int32),
                f"cell_type == 'MN_{leg}_{mgrp}'",
            )

    cells = CellTable(
        source_id=np.arange(1000, 1000 + n_total, dtype=np.int64),
        species_names=("synthetic_cns_embodied",),
        species_idx=np.zeros(n_total, dtype=np.uint8),
        cell_type=tuple(types),
        super_class=tuple(super_classes),
        cell_class=tuple(classes),
        cell_sub_class=tuple(sub_classes),
        region=tuple(regions),
        side=tuple(sides),
        role=np.asarray(roles, dtype=np.uint8),
        cell_model=np.full(n_total, MODEL_SPIKING_LIF, dtype=np.uint8),
        neurotransmitter=tuple(nts),
        position_nm=np.asarray(xyz, dtype=np.float32),
        position_source=np.full(n_total, POS_SOMA, dtype=np.uint8),
    )

    edge_rows: list[tuple[int, int, int, int]] = [
        (
            int(base.edges.pre[i]),
            int(base.edges.post[i]),
            int(base.edges.count[i]),
            int(base.edges.sign[i]),
        )
        for i in range(base.edges.num_edges)
    ]
    tripod_a = {0, 4, 2}  # LF, RM, LH
    tripod_b = {3, 1, 5}  # RF, LM, RH
    # DNp09 (20) excites all 6 VNC premotor neurons; DNg84 (18, 19) inhibits hind/mid premotors
    for li in range(6):
        pm = 30 + li
        pr = 24 + li
        mn_base = 36 + li * 6
        # Descending drive from DNp09 -> VNC premotor
        edge_rows.append((20, pm, 65 if li in tripod_a else 55, 1))
        # Turning DNa01 L (21) / R (22) modulate contralateral premotor drive
        if li < 3:  # left legs
            edge_rows.append((22, pm, 35, 1))
        else:  # right legs
            edge_rows.append((21, pm, 35, 1))
        # Proprioceptive load inhibits stance premotor and excites contralateral tripod
        edge_rows.append((pr, pm, 48, -1))
        partners = tripod_b if li in tripod_a else tripod_a
        for opp in partners:
            edge_rows.append((pr, 30 + opp, 24, 1))
            edge_rows.append((pm, 30 + opp, 40, -1))
        # Premotor excites swing muscles (coxa_pro=0, fem_flex=2, tib_ext=4);
        # proprioceptor + opposing tripod excite stance muscles (coxa_ret=1, fem_ext=3, tib_flex=5).
        edge_rows.append((pm, mn_base + 0, 75, 1))
        edge_rows.append((pm, mn_base + 2, 75, 1))
        edge_rows.append((pm, mn_base + 4, 55, 1))
        edge_rows.append((pr, mn_base + 1, 60, 1))
        edge_rows.append((pr, mn_base + 3, 60, 1))
        edge_rows.append((pr, mn_base + 5, 65, 1))

    edges = EdgeTable(
        pre=np.array([r[0] for r in edge_rows], dtype=np.int32),
        post=np.array([r[1] for r in edge_rows], dtype=np.int32),
        count=np.array([r[2] for r in edge_rows], dtype=np.int32),
        sign=np.array([r[3] for r in edge_rows], dtype=np.int8),
        kind=np.full(len(edge_rows), SYNAPSE_CHEMICAL, dtype=np.uint8),
    )
    prov = DatasetProvenance(
        dataset_id="synthetic_cns_embodied",
        species="Synthetic embodied Drosophila Brain+VNC spiking CNS",
        version="f8-l2-v1",
        citation="Built-in 72-neuron offline Brain+VNC circuit mirroring BANC/MaleCNS F8 L2 ports",
        licence_note="Internal ALife Lab test fixture",
        files=(),
    )
    digest = compute_pack_digest(
        "synthetic_cns_embodied", prov.species, cells, edges, io_ports, prov
    )
    return ConnectomePack(
        dataset_id="synthetic_cns_embodied",
        species=prov.species,
        cells=cells,
        edges=edges,
        io_ports=io_ports,
        provenance=prov,
        pack_digest=digest,
    )


@dataclass(frozen=True)
class EmbodiedPorts:
    """Resolved neuron index arrays linking body sensors <-> brain/VNC <-> motor commands."""

    sugar_grn: I32
    bitter_grn: I32
    groom_mech: I32
    odor_left: I32
    odor_right: I32
    forward_dn: I32
    turn_left_dn: I32
    turn_right_dn: I32
    backward_dn: I32
    proboscis_mn: I32
    grooming_dn: I32
    all_sensory_union: I32
    all_command_union: I32
    # Offsets into all_command_union for fast single-read decoding:
    cmd_slices: dict[str, tuple[int, int]]
    # Phase F8 Level 2 VNC ports (empty on brain-only packs like FlyWire v783):
    has_vnc_ports: bool = False
    proprio_ports: dict[str, I32] = field(default_factory=dict)
    leg_mn_slices: dict[tuple[str, str], tuple[int, int]] = field(default_factory=dict)


def resolve_embodied_ports(pack: ConnectomePack) -> EmbodiedPorts:
    """Resolve sensory, descending, brain motor, and VNC 36-channel leg motor neuron indices."""
    cells = pack.cells
    n = cells.num_cells

    def _port_or(pid: str, pred: Any) -> I32:
        if pid in pack.io_ports and pack.io_ports[pid].cell_indices.size > 0:
            return pack.io_ports[pid].cell_indices.astype(np.int32, copy=False)
        return np.asarray([i for i in range(n) if pred(i)], dtype=np.int32)

    sugar = _port_or("sugar_grn", lambda i: False)
    bitter = _port_or("bitter_grn", lambda i: False)
    groom_mech = _port_or("antennal_grooming_mechanosensory", lambda i: False)

    # Bilateral food-odor ORN subset (attractive glomeruli DM1/DM2/DM4/VA2 when available,
    # capped at 16 per side so the antennal lobe & MB light up cleanly without asymmetric flooding).
    olf_all = _port_or("olfactory_sensory", lambda i: False)
    food_gloms = {"ORN_DM1", "ORN_DM2", "ORN_DM4", "ORN_VA2"}
    olf_l = np.asarray(
        [
            int(i)
            for i in olf_all
            if cells.side[int(i)] == "left" and cells.cell_type[int(i)] in food_gloms
        ][:16],
        dtype=np.int32,
    )
    olf_r = np.asarray(
        [
            int(i)
            for i in olf_all
            if cells.side[int(i)] == "right" and cells.cell_type[int(i)] in food_gloms
        ][:16],
        dtype=np.int32,
    )
    if olf_l.size == 0 or olf_r.size == 0:
        olf_l = np.asarray(
            [int(i) for i in olf_all if cells.side[int(i)] == "left"][:16], dtype=np.int32
        )
        olf_r = np.asarray(
            [int(i) for i in olf_all if cells.side[int(i)] == "right"][:16], dtype=np.int32
        )
    if olf_l.size == 0 and olf_all.size > 0:
        half = max(1, olf_all.size // 2)
        olf_l, olf_r = olf_all[:half], olf_all[half:]

    fwd = _port_or("forward_dn", lambda i: cells.cell_type[i] == "DNp09")
    t_l = _port_or(
        "turn_left_dn",
        lambda i: cells.cell_type[i] in ("DNa01", "DNa02") and cells.side[i] == "left",
    )
    t_r = _port_or(
        "turn_right_dn",
        lambda i: cells.cell_type[i] in ("DNa01", "DNa02") and cells.side[i] == "right",
    )
    bwd = _port_or("backward_dn", lambda i: cells.cell_type[i] == "MDN")
    prob = _port_or("mn9_proboscis_extension", lambda i: cells.cell_type[i] in ("CB0701", "MN9"))
    groom_dn = _port_or("grooming_dn", lambda i: cells.cell_type[i] == "DNg84")

    # VNC proprioceptors (6 legs) & 36 antagonist leg motor neuron pools
    proprio_ports: dict[str, I32] = {}
    for leg in LEG_NAMES:
        pid = f"proprio_{leg}"
        if pid in pack.io_ports and pack.io_ports[pid].cell_indices.size > 0:
            # Cap at 64 proprioceptors per leg to keep sensory upload minimal & balanced.
            proprio_ports[leg] = pack.io_ports[pid].cell_indices[:64].astype(np.int32, copy=False)

    sens_parts = [sugar, bitter, groom_mech, olf_l, olf_r, fwd, t_l, t_r, *proprio_ports.values()]
    sens_union = (
        np.unique(np.concatenate(sens_parts)) if sens_parts else np.zeros(0, dtype=np.int32)
    )

    # Pack command & VNC motor neuron indices contiguously for a single < 2 KB GPU->CPU read!
    cmd_parts = [
        ("forward", fwd),
        ("turn_left", t_l),
        ("turn_right", t_r),
        ("backward", bwd),
        ("proboscis", prob),
        ("grooming", groom_dn),
    ]
    cmd_slices: dict[str, tuple[int, int]] = {}
    cat_list: list[I32] = []
    pos = 0
    for cname, arr in cmd_parts:
        cmd_slices[cname] = (pos, pos + int(arr.size))
        cat_list.append(arr)
        pos += int(arr.size)

    leg_mn_slices: dict[tuple[str, str], tuple[int, int]] = {}
    vnc_mn_total = 0
    for leg in LEG_NAMES:
        for mgrp in MUSCLE_CHANNELS:
            pid = f"mn_{leg}_{mgrp}"
            if pid in pack.io_ports and pack.io_ports[pid].cell_indices.size > 0:
                arr = pack.io_ports[pid].cell_indices.astype(np.int32, copy=False)
                leg_mn_slices[(leg, mgrp)] = (pos, pos + int(arr.size))
                cat_list.append(arr)
                pos += int(arr.size)
                vnc_mn_total += int(arr.size)
            else:
                leg_mn_slices[(leg, mgrp)] = (pos, pos)

    cmd_union = np.concatenate(cat_list) if cat_list else np.zeros(0, dtype=np.int32)

    return EmbodiedPorts(
        sugar_grn=sugar,
        bitter_grn=bitter,
        groom_mech=groom_mech,
        odor_left=olf_l,
        odor_right=olf_r,
        forward_dn=fwd,
        turn_left_dn=t_l,
        turn_right_dn=t_r,
        backward_dn=bwd,
        proboscis_mn=prob,
        grooming_dn=groom_dn,
        all_sensory_union=sens_union.astype(np.int32, copy=False),
        all_command_union=cmd_union.astype(np.int32, copy=False),
        cmd_slices=cmd_slices,
        has_vnc_ports=vnc_mn_total > 0,
        proprio_ports=proprio_ports,
        leg_mn_slices=leg_mn_slices,
    )


@dataclass
class TimingStats:
    """Running EMA wall-time breakdown per 1 ms closed-loop tick (ms)."""

    brain_ms: float = 0.0
    body_ms: float = 0.0
    transfer_ms: float = 0.0
    total_ms: float = 0.0
    samples: int = 0

    def update(self, brain_ms: float, body_ms: float, transfer_ms: float) -> None:
        tot = brain_ms + body_ms + transfer_ms
        if self.samples == 0:
            self.brain_ms = brain_ms
            self.body_ms = body_ms
            self.transfer_ms = transfer_ms
            self.total_ms = tot
        else:
            a = 0.08
            self.brain_ms = (1 - a) * self.brain_ms + a * brain_ms
            self.body_ms = (1 - a) * self.body_ms + a * body_ms
            self.transfer_ms = (1 - a) * self.transfer_ms + a * transfer_ms
            self.total_ms = (1 - a) * self.total_ms + a * tot
        self.samples += 1

    @property
    def realtime_factor(self) -> float:
        return round(1.0 / max(self.total_ms, 1e-4), 3) if self.samples > 0 else 0.0


