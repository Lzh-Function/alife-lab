"""Phase F8 Level 1: Closed-loop Brain <-> Body embodied fly engine.

Connects a spiking LIF connectome brain (either the full 138,639-neuron FlyWire v783 adult
*Drosophila* brain on GPU CUDA graphs / CPU NumPy, OR the built-in 24-neuron offline
``synthetic_fly_embodied`` circuit for CPU-only CI) to the MuJoCo 6-legged fly body and Level 1
hand-crafted tripod CPG (``fly_body.py``).

Every 1 ms tick:
1. Body sensors sample the arena (taste, bilateral antennal odor plume, antennal touch).
2. Sensory firing rates drive the brain's anatomical sensory ports (combined with any user
   ``stimulate`` / ``silence`` interventions).
3. The LIF brain advances 1 ms (10 x 0.1 ms substeps, bitwise identical CPU/GPU).
4. Descending & motor command spikes (``DNp09``, ``DNa01``/``DNa02``, ``MDN``, ``CB0701``/MN9,
   ``DNg84``/``DNg35``) are read back (< 1 KB transfer) and low-pass filtered into motor commands.
5. The Level 1 tripod CPG + MuJoCo body advances 1 ms (2 x 0.5 ms physics substeps).
"""

