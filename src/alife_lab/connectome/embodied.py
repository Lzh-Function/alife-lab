def make_embodied_world(
    pack: ConnectomePack,
    *,
    wiring: str = "reference",
    seed: int = 1,
    backend: str = "numpy",
    foods: list[FoodSpot] | None = None,
    arena_half_size: float = 6.0,
    explore_drive_hz: float = 110.0,
    control_mode: str = "level1_cpg",
    vnc_synapse_scale: float = 1.0,
    vnc_proprio_gain_hz: float = 95.0,
    vnc_mn_norm_hz: float = 30.0,
    vnc_coxa_gain: float = 0.45,
    vnc_femur_gain: float = 0.55,
    vnc_tibia_gain: float = 0.50,
    datasets_dir: Path | None = None,
) -> EmbodiedFlyWorld:
    """Initialize a deterministic closed-loop Brain(+VNC) <-> Body embodied fly world."""
    csr = pack.edges.to_csr(pack.cells.num_cells)
    if wiring == "shuffled_control":
        csr = make_shuffled_csr(csr, int(seed))
    base_params = LIFParams()
    # In Level 2 VNC modes, vnc_synapse_scale adjusts the global single-synapse PSP (w_syn)
    # while keeping the biological wiring topology 100% untouched.
    params = (
        LIFParams(w_syn_mv=float(base_params.w_syn_mv) * float(vnc_synapse_scale))
        if control_mode != "level1_cpg" and abs(float(vnc_synapse_scale) - 1.0) > 1e-6
        else base_params
    )
    lif = make_initial_state(pack.cells.num_cells, params)
    ports = resolve_embodied_ports(pack)
    if control_mode != "level1_cpg" and not ports.has_vnc_ports:
        raise ValueError(
            f"control_mode={control_mode!r} requires a whole-CNS connectome with VNC leg motor "
            f"neurons (e.g. 'banc_888', 'male_cns_v1', 'synthetic_cns_embodied'); "
            f"{pack.dataset_id!r} has no VNC motor ports"
        )
    body = make_fly_body(datasets_dir=datasets_dir)
    arena = ArenaState(
        arena_half_size=float(arena_half_size),
        foods=list(foods)
        if foods is not None
        else [FoodSpot(x=1.25, y=0.25, radius=0.36, kind="sugar")],
    )
    x0, y0, _ = fly_pose_xy_yaw(body)
    arena.trail.append([round(x0, 3), round(y0, 3)])

    gpu_runner: Any = None
    if backend == "cupy":
        from alife_lab.connectome.lif_cupy import CupyLIFRunner

        gpu_runner = CupyLIFRunner(csr, params, seed=int(seed))
        gpu_runner.upload_state(lif)

    return EmbodiedFlyWorld(
        pack=pack,
        csr=csr,
        ports=ports,
        params=params,
        lif=lif,
        body=body,
        arena=arena,
        seed=int(seed),
        backend=backend,
        wiring=wiring,
        control_mode=control_mode,
        explore_drive_hz=float(explore_drive_hz),
        vnc_synapse_scale=float(vnc_synapse_scale),
        vnc_proprio_gain_hz=float(vnc_proprio_gain_hz),
        vnc_mn_norm_hz=float(vnc_mn_norm_hz),
        vnc_coxa_gain=float(vnc_coxa_gain),
        vnc_femur_gain=float(vnc_femur_gain),
        vnc_tibia_gain=float(vnc_tibia_gain),
        gpu_runner=gpu_runner,
        gpu_synced_to_host=True,
        manual_stim_hz=np.zeros(pack.cells.num_cells, dtype=np.float32),
        prev_xy=(x0, y0),
    )


def step_embodied_tick(world: EmbodiedFlyWorld) -> MotorCommands:
    """Execute one coupled 1 ms Brain <-> Body tick and record exact per-stage wall latency."""
    t0 = time.perf_counter()

    # 1. Sample body sensors from MuJoCo arena.
    sensors = sense_environment(world.body, world.arena)
    world.last_sensors = sensors
    p = world.ports

    # 2. Compute sensory firing rates (manual user stim + closed-loop body sensory rates).
    stim = world.lif.stim_rate_hz
    u_idx = p.all_sensory_union
    stim[u_idx] = world.manual_stim_hz[u_idx]

    if sensors.sugar_contact > 0.0 and p.sugar_grn.size > 0:
        stim[p.sugar_grn] = np.maximum(stim[p.sugar_grn], np.float32(190.0 * sensors.sugar_contact))
    if sensors.bitter_contact > 0.0 and p.bitter_grn.size > 0:
        stim[p.bitter_grn] = np.maximum(
            stim[p.bitter_grn], np.float32(200.0 * sensors.bitter_contact)
        )
    if sensors.antennal_touch > 0.0 and p.groom_mech.size > 0:
        stim[p.groom_mech] = np.maximum(
            stim[p.groom_mech], np.float32(210.0 * sensors.antennal_touch)
        )
    # On small synthetic circuits, raw bilateral ORNs directly drive DNa01 steering.
    # On full FlyWire v783 (uniform-weight Shiu LIF without APL divisive inhibition), sustained
    # raw ORN firing ignites a whole-brain KC/GABA cascade that tonically suppresses MN9
    # (measured: 45 -> 2 MN9 spikes after 500 ms pre-odor), so FlyWire chemotaxis routes
    # bilateral odor contrast directly into DNa01/02 steering neurons (see fidelity report).
    if world.pack.cells.num_cells < 1000:
        if sensors.odor_left > 0.02 and p.odor_left.size > 0:
            stim[p.odor_left] = np.maximum(stim[p.odor_left], np.float32(90.0 * sensors.odor_left))
        if sensors.odor_right > 0.02 and p.odor_right.size > 0:
            stim[p.odor_right] = np.maximum(
                stim[p.odor_right], np.float32(90.0 * sensors.odor_right)
            )

    # Exploratory arousal onto DNp09 & contrast-normalized chemotactic steering onto DNa01/02.
    # Suppress baseline walking arousal when tasting sweet food (without bitter) so the fly slows
    # naturally as MN9 engages, instead of zipping past the droplet.
    if world.explore_drive_hz > 0.0 and p.forward_dn.size > 0:
        walk_drive = (
            world.explore_drive_hz * 0.12
            if (sensors.sugar_contact > 0.2 and sensors.bitter_contact <= 0.05)
            else world.explore_drive_hz
        )
        stim[p.forward_dn] = np.maximum(stim[p.forward_dn], np.float32(walk_drive))

    odor_sum = sensors.odor_left + sensors.odor_right
    odor_diff = sensors.odor_left - sensors.odor_right
    if odor_sum > 0.04 and sensors.sugar_contact <= 0.05:
        contrast = odor_diff / max(0.08, odor_sum)
        # Bilateral Weber-contrast steering into DNa01/02 (like LAL PFL3 chemotaxis amplification)
        # so even a 0.5% left-right odor gradient steers cleanly straight into the honey droplet.
        if contrast > 0.0012 and p.turn_left_dn.size > 0:
            gain = min(200.0, 22000.0 * contrast)
            stim[p.turn_left_dn] = np.maximum(stim[p.turn_left_dn], np.float32(gain))
        elif contrast < -0.0012 and p.turn_right_dn.size > 0:
            gain = min(200.0, 22000.0 * (-contrast))
            stim[p.turn_right_dn] = np.maximum(stim[p.turn_right_dn], np.float32(gain))

    # Phase F8 Level 2: Closed-loop leg proprioception -> VNC sensory ports (LF..RH).
    proprio = proprioceptive_feedback(world.body, sensors)
    world.last_proprio = proprio
    if world.control_mode != "level1_cpg" and world.vnc_proprio_gain_hz > 0.0:
        for li, leg in enumerate(LEG_NAMES):
            p_idx = p.proprio_ports.get(leg)
            if p_idx is not None and p_idx.size > 0 and proprio[li] > 0.01:
                stim[p_idx] = np.maximum(
                    stim[p_idx], np.float32(world.vnc_proprio_gain_hz * proprio[li])
                )

    t_xfer0 = time.perf_counter()
    if world.gpu_runner is not None:
        world.gpu_runner.upload_stim_subset(u_idx, stim[u_idx])
    t_brain0 = time.perf_counter()

    # 3. Step spiking LIF brain 1 ms (10 x 0.1 ms substeps).
    if world.gpu_runner is not None:
        world.gpu_runner.step_tick()
        world.lif.tick += 1
        world.lif.substep += world.params.substeps_per_tick
        world.gpu_synced_to_host = False
        t_brain1 = time.perf_counter()
        cmd_spikes = world.gpu_runner.read_spike_subset(p.all_command_union)
    else:
        step_tick_cpu(world.lif, world.csr, world.params, world.seed)
        t_brain1 = time.perf_counter()
        cmd_spikes = world.lif.last_tick_spikes[p.all_command_union]
    t_body0 = time.perf_counter()

    # Mask silenced output/descending neurons (silenced = outgoing axon transmission blocked).
    if p.all_command_union.size > 0:
        cmd_spikes = cmd_spikes * (world.lif.silenced[p.all_command_union] == 0)

    # 4. Exponential low-pass filter of descending/motor spikes (tau = 30 ms -> Hz).
    decay = math.exp(-1.0 / 30.0)
    alpha = 1.0 - decay

    def _inst_hz(name: str) -> float:
        lo, hi = p.cmd_slices[name]
        cnt = hi - lo
        if cnt <= 0:
            return 0.0
        # 1 spike in 1 ms = 1000 Hz instantaneous rate per neuron.
        return float(cmd_spikes[lo:hi].sum()) * (1000.0 / cnt)

    world.rate_forward = decay * world.rate_forward + alpha * _inst_hz("forward")
    world.rate_turn_left = decay * world.rate_turn_left + alpha * _inst_hz("turn_left")
    world.rate_turn_right = decay * world.rate_turn_right + alpha * _inst_hz("turn_right")
    world.rate_backward = decay * world.rate_backward + alpha * _inst_hz("backward")
    world.rate_proboscis = decay * world.rate_proboscis + alpha * _inst_hz("proboscis")
    world.rate_grooming = decay * world.rate_grooming + alpha * _inst_hz("grooming")

    # Normalize smoothed Hz into [0, 1] motor command meters
    # (calibrated to measured FlyWire v783 rates: MN9 ~70-120 Hz on sugar, DNg84 ~45-100 Hz).
    cmd = MotorCommands(
        forward=min(1.0, world.rate_forward / 75.0),
        turn=max(-1.0, min(1.0, (world.rate_turn_left - world.rate_turn_right) / 60.0)),
        backward=min(1.0, world.rate_backward / 60.0),
        proboscis=min(1.0, world.rate_proboscis / 55.0),
        grooming=min(1.0, world.rate_grooming / 28.0),
    )
    world.last_commands = cmd

    # Decode 36-channel VNC leg motor neuron pools whenever present (tau = 20 ms -> Hz).
    if p.has_vnc_ports:
        mn_decay = math.exp(-1.0 / 20.0)
        mn_alpha = 1.0 - mn_decay
        for li, leg in enumerate(LEG_NAMES):
            for mi, mgrp in enumerate(MUSCLE_CHANNELS):
                lo, hi = p.leg_mn_slices[(leg, mgrp)]
                cnt = hi - lo
                inst = float(cmd_spikes[lo:hi].sum()) * (1000.0 / cnt) if cnt > 0 else 0.0
                world.leg_mn_rates[li, mi] = np.float32(
                    mn_decay * float(world.leg_mn_rates[li, mi]) + mn_alpha * inst
                )
        # Measure Tripod A {LF(0), RM(4), LH(2)} vs Tripod B {RF(3), LM(1), RH(5)} balance:
        leg_tot = world.leg_mn_rates.mean(axis=1)
        trip_a = float(leg_tot[0] + leg_tot[4] + leg_tot[2]) / 3.0
        trip_b = float(leg_tot[3] + leg_tot[1] + leg_tot[5]) / 3.0
        denom = trip_a + trip_b
        world.last_vnc_tripod_alt = abs(trip_a - trip_b) / denom if denom > 0.2 else 0.0

    # 5. Step MuJoCo body 1 ms: Level 1 hand-crafted tripod CPG OR Level 2 direct VNC MNs!
    if world.control_mode == "level1_cpg":
        step_body_1ms(world.body, world.arena, cmd, sensors)
    else:
        # Decode 18 joint actuator targets directly from 36 antagonist VNC motor neuron pools:
        #   coxa_yaw    = -side * coxa_gain  * tanh((coxa_pro - coxa_ret) / norm)
        #   femur_pitch =  0.16 - femur_gain * tanh((fem_flex - fem_ext) / norm)  (- lifts UP!)
        #   tibia_pitch = -0.08 + tibia_gain * tanh((tib_ext  - tib_flex) / norm)
        norm_hz = max(1.0, float(world.vnc_mn_norm_hz))
        leg_ctrl = np.zeros(18, dtype=np.float64)
        for li, leg in enumerate(LEG_NAMES):
            side_sign = 1.0 if leg.startswith("L") else -1.0
            r = world.leg_mn_rates[li]
            coxa_net = math.tanh((float(r[0]) - float(r[1])) / norm_hz)
            fem_net = math.tanh((float(r[2]) - float(r[3])) / norm_hz)
            tib_net = math.tanh((float(r[4]) - float(r[5])) / norm_hz)
            base = li * 3
            leg_ctrl[base + 0] = -side_sign * world.vnc_coxa_gain * coxa_net
            leg_ctrl[base + 1] = 0.16 - world.vnc_femur_gain * fem_net
            leg_ctrl[base + 2] = -0.08 + world.vnc_tibia_gain * tib_net
        head_pitch = 0.14 * cmd.proboscis if cmd.proboscis >= 0.30 else (0.30 * cmd.grooming)
        step_body_level2_vnc_1ms(world.body, world.arena, leg_ctrl, cmd.proboscis, head_pitch)
    t_end = time.perf_counter()

    # Track behavioral counters & trail.
    if cmd.proboscis >= 0.30 and cmd.grooming < 0.30:
        world.total_feeding_ms += 1
    if cmd.grooming >= 0.30:
        world.total_grooming_ms += 1
    x, y, _ = fly_pose_xy_yaw(world.body)
    world.distance_traveled += math.hypot(x - world.prev_xy[0], y - world.prev_xy[1])
    world.prev_xy = (x, y)
    if world.tick % 20 == 0:
        world.arena.trail.append([round(x, 3), round(y, 3)])
        if len(world.arena.trail) > 250:
            del world.arena.trail[:-250]

    transfer_ms = ((t_brain0 - t_xfer0) + (t_body0 - t_brain1)) * 1e3
    brain_ms = (t_brain1 - t_brain0) * 1e3
    body_ms = (t_end - t_body0) * 1e3 + (t_xfer0 - t0) * 1e3
    world.timing.update(brain_ms=brain_ms, body_ms=body_ms, transfer_ms=transfer_ms)
    return cmd


def run_embodied_verification(
    pack: ConnectomePack,
    *,
    backend: str = "numpy",
    seed: int = 1,
    ticks_per_scene: int = 250,
    datasets_dir: Path | None = None,
) -> dict[str, Any]:
    """Run all 4 F8 acceptance scenes & negative controls + measure real-time latency breakdown.

    Scenes (connectome_plan.md §4 F8 acceptance gates):
    1. ``sugar_feeding``: fly over sugar spot -> MN9 fires, proboscis extends, walking pauses.
    2. ``bitter_suppression``: sugar + bitter spot -> MN9 suppressed vs sugar alone.
    3. ``antennal_grooming``: antennal poke -> DNg84 fires, grooming engages.
    4. ``silenced_mn9`` & ``shuffled_control``: silencing MN9 / shuffling wiring breaks reflexes.
    """
    t_all = time.perf_counter()

    def _run_scene(
        wiring: str,
        foods: list[FoodSpot],
        *,
        poke_ms: int = 0,
        silence_port: str | None = None,
    ) -> dict[str, Any]:
        w = make_embodied_world(
            pack,
            wiring=wiring,
            seed=seed,
            backend=backend,
            foods=foods,
            explore_drive_hz=90.0,
            datasets_dir=datasets_dir,
        )
        w.arena.poke_remaining_ms = poke_ms
        if silence_port is not None and silence_port in pack.io_ports:
            w.lif.silenced[pack.io_ports[silence_port].cell_indices] = 1
            if w.gpu_runner is not None:
                w.gpu_runner.upload_controls(w.lif)

        max_prob = 0.0
        max_groom = 0.0
        max_prob_joint = 0.0
        for _ in range(ticks_per_scene):
            cmd = step_embodied_tick(w)
            max_prob = max(max_prob, cmd.proboscis)
            max_groom = max(max_groom, cmd.grooming)
            max_prob_joint = max(
                max_prob_joint, float(w.body.data.qpos[w.body.proboscis_joint_qpos_adr])
            )
        return {
            "wiring": wiring,
            "ticks": ticks_per_scene,
            "max_proboscis_cmd": round(max_prob, 4),
            "max_proboscis_joint_rad": round(max_prob_joint, 4),
            "feeding_ms": w.total_feeding_ms,
            "max_grooming_cmd": round(max_groom, 4),
            "grooming_ms": w.total_grooming_ms,
            "distance_cm": round(w.distance_traveled, 4),
            "timing_ms": {
                "brain_ms": round(w.timing.brain_ms, 4),
                "body_ms": round(w.timing.body_ms, 4),
                "transfer_ms": round(w.timing.transfer_ms, 4),
                "total_ms": round(w.timing.total_ms, 4),
                "realtime_factor": w.timing.realtime_factor,
            },
            "body_asset": w.body.asset_info,
        }

    # Scene 1: Sugar food right beneath head/tarsi (x=0.25, y=0).
    s_sugar = _run_scene("reference", [FoodSpot(0.25, 0.0, 0.50, "sugar")])
    # Scene 2: Sugar + Bitter co-located (bitter suppresses feeding!).
    s_bitter = _run_scene(
        "reference",
        [FoodSpot(0.25, 0.0, 0.50, "sugar"), FoodSpot(0.25, 0.0, 0.50, "bitter")],
    )
    # Scene 3: Antennal poke -> grooming!
    s_groom = _run_scene("reference", [], poke_ms=ticks_per_scene)
    # Scene 4a: Negative control — silence MN9 on sugar food -> no proboscis extension!
    s_silenced = _run_scene(
        "reference",
        [FoodSpot(0.25, 0.0, 0.50, "sugar")],
        silence_port="mn9_proboscis_extension",
    )
    # Scene 4b: Negative control — shuffled connectome on sugar + poke -> both reflexes break.
    s_shuf_sugar = _run_scene("shuffled_control", [FoodSpot(0.25, 0.0, 0.50, "sugar")])
    s_shuf_groom = _run_scene("shuffled_control", [], poke_ms=ticks_per_scene)

    checks = {
        "sugar_triggers_feeding": s_sugar["max_proboscis_cmd"] >= 0.45
        and s_sugar["feeding_ms"] > 50,
        "bitter_suppresses_feeding": s_bitter["feeding_ms"] < s_sugar["feeding_ms"] * 0.5,
        "antenna_poke_triggers_grooming": s_groom["max_grooming_cmd"] >= 0.45
        and s_groom["grooming_ms"] > 50,
        "mn9_silencing_breaks_feeding": s_silenced["feeding_ms"] == 0,
        "shuffled_wiring_breaks_feeding": s_shuf_sugar["feeding_ms"] < s_sugar["feeding_ms"] * 0.35,
        "shuffled_wiring_breaks_grooming": s_shuf_groom["grooming_ms"]
        < s_groom["grooming_ms"] * 0.25,
    }
    return {
        "dataset_id": pack.dataset_id,
        "num_cells": pack.cells.num_cells,
        "num_edges": pack.edges.num_edges,
        "backend": backend,
        "seed": seed,
        "framing_note": EMBODIED_LEVEL1_FRAMING,
        "wall_seconds": round(time.perf_counter() - t_all, 3),
        "all_checks_passed": all(checks.values()),
        "checks": checks,
        "scenes": {
            "sugar_feeding": s_sugar,
            "bitter_suppression": s_bitter,
            "antennal_grooming": s_groom,
            "silenced_mn9": s_silenced,
            "shuffled_sugar": s_shuf_sugar,
            "shuffled_grooming": s_shuf_groom,
        },
    }


def run_embodied_level2_verification(
    pack: ConnectomePack,
    *,
    backend: str = "numpy",
    seed: int = 1,
    ticks_per_scene: int = 400,
    control_mode: str = "level2_vnc",
    vnc_synapse_scale: float = 1.0,
    vnc_proprio_gain_hz: float = 95.0,
    vnc_mn_norm_hz: float = 30.0,
    datasets_dir: Path | None = None,
) -> dict[str, Any]:
    """Run F8 Level 2 VNC direct-drive verification & negative controls (NO hand-crafted CPG).

    Evaluates:
    1. ``vnc_intact``: closed-loop Brain + VNC + proprioception + MuJoCo physics.
    2. ``vnc_open_loop``: proprioceptive feedback disabled (``vnc_proprio_gain_hz=0``).
    3. ``vnc_shuffled``: degree-preserving shuffled connectome control.
    4. ``vnc_dn_silenced``: ``forward_dn`` (DNp09) silenced.
    5. Honest real-time factor, leg MN rates (Hz), tripod alternation, and distance walked.
    """
    t_all = time.perf_counter()

    def _run_l2(
        wiring: str,
        *,
        proprio_hz: float,
        silence_dn: bool = False,
        explore_hz: float = 140.0,
    ) -> dict[str, Any]:
        w = make_embodied_world(
            pack,
            wiring=wiring,
            seed=seed,
            backend=backend,
            foods=[FoodSpot(1.25, 0.25, 0.36, "sugar")],
            explore_drive_hz=explore_hz,
            control_mode=control_mode,
            vnc_synapse_scale=vnc_synapse_scale,
            vnc_proprio_gain_hz=proprio_hz,
            vnc_mn_norm_hz=vnc_mn_norm_hz,
            datasets_dir=datasets_dir,
        )
        if silence_dn and w.ports.forward_dn.size > 0:
            w.lif.silenced[w.ports.forward_dn] = np.uint8(1)
            if w.gpu_runner is not None:
                w.gpu_runner.upload_controls(w.lif)

        mn_samples: list[float] = []
        alt_samples: list[float] = []
        swing_transitions = 0
        prev_contacts: tuple[bool, ...] = (True,) * 6
        for _ in range(ticks_per_scene):
            step_embodied_tick(w)
            mn_samples.append(w.vnc_mn_mean_hz)
            alt_samples.append(w.last_vnc_tripod_alt)
            cur_c = w.last_sensors.tarsus_contacts
            swing_transitions += sum(1 for a, b in zip(prev_contacts, cur_c, strict=True) if a != b)
            prev_contacts = cur_c

        per_leg_hz = {
            leg: round(float(w.leg_mn_rates[li].mean()), 2) for li, leg in enumerate(LEG_NAMES)
        }
        return {
            "wiring": wiring,
            "ticks": ticks_per_scene,
            "distance_cm": round(w.distance_traveled, 4),
            "vnc_mn_mean_hz": round(float(np.mean(mn_samples)), 3),
            "vnc_mn_peak_hz": round(float(np.max(mn_samples)), 3),
            "vnc_tripod_alternation_mean": round(float(np.mean(alt_samples)), 4),
            "tarsus_contact_transitions": int(swing_transitions),
            "per_leg_mn_hz": per_leg_hz,
            "timing_ms": {
                "brain_ms": round(w.timing.brain_ms, 4),
                "body_ms": round(w.timing.body_ms, 4),
                "transfer_ms": round(w.timing.transfer_ms, 4),
                "total_ms": round(w.timing.total_ms, 4),
                "realtime_factor": w.timing.realtime_factor,
            },
        }

    s_intact = _run_l2("reference", proprio_hz=vnc_proprio_gain_hz)
    s_open = _run_l2("reference", proprio_hz=0.0)
    s_shuf = _run_l2("shuffled_control", proprio_hz=vnc_proprio_gain_hz)
    s_sil = _run_l2("reference", proprio_hz=vnc_proprio_gain_hz, silence_dn=True)

    checks = {
        "vnc_mns_recruited": s_intact["vnc_mn_peak_hz"] >= 0.5,
        "proprioception_modulates_vnc": abs(s_intact["vnc_mn_mean_hz"] - s_open["vnc_mn_mean_hz"])
        > 0.05
        or abs(s_intact["distance_cm"] - s_open["distance_cm"]) > 0.005,
        "shuffled_vnc_differs_from_intact": abs(
            s_intact["vnc_mn_mean_hz"] - s_shuf["vnc_mn_mean_hz"]
        )
        > 0.1
        or abs(s_intact["distance_cm"] - s_shuf["distance_cm"]) > 0.01,
        "dn_silencing_changes_vnc_output": abs(s_intact["vnc_mn_mean_hz"] - s_sil["vnc_mn_mean_hz"])
        > 0.05
        or abs(s_intact["distance_cm"] - s_sil["distance_cm"]) > 0.005,
    }
    return {
        "dataset_id": pack.dataset_id,
        "control_mode": control_mode,
        "vnc_synapse_scale": vnc_synapse_scale,
        "vnc_proprio_gain_hz": vnc_proprio_gain_hz,
        "vnc_mn_norm_hz": vnc_mn_norm_hz,
        "num_cells": pack.cells.num_cells,
        "num_edges": pack.edges.num_edges,
        "backend": backend,
        "seed": seed,
        "framing_note": (
            EMBODIED_LEVEL2_TUNED_FRAMING
            if control_mode == "level2_vnc_tuned"
            else EMBODIED_LEVEL2_FRAMING
        ),
        "wall_seconds": round(time.perf_counter() - t_all, 3),
        "all_checks_passed": all(checks.values()),
        "checks": checks,
        "scenes": {
            "vnc_intact": s_intact,
            "vnc_open_loop": s_open,
            "vnc_shuffled": s_shuf,
            "vnc_dn_silenced": s_sil,
        },
    }


def tune_vnc_locomotion(
    pack: ConnectomePack,
    *,
    backend: str = "numpy",
    seed: int = 1,
    ticks_per_eval: int = 500,
    datasets_dir: Path | None = None,
) -> dict[str, Any]:
    """Fixed-topology search over global VNC synaptic & readout gains (intact vs shuffled VNC).

    Keeps the biological Brain+VNC wiring graph 100% untouched (ZERO added edges, ZERO hand-crafted
    CPG) and searches over ``(vnc_synapse_scale, vnc_proprio_gain_hz, explore_drive_hz)`` to
    measure how much locomotion & tripod alternation emerge on the real connectome vs shuffled.
    """
    t0 = time.perf_counter()
    # Grid of biologically plausible single-synapse PSP scales & proprioceptive feedback gains.
    candidates: list[tuple[float, float, float]] = [
        (1.0, 95.0, 140.0),
        (1.5, 95.0, 160.0),
        (2.0, 120.0, 180.0),
        (2.5, 140.0, 200.0),
        (3.2, 140.0, 200.0),
        (0.75, 120.0, 180.0),
    ]

    def _eval(wiring: str, syn_s: float, prop_hz: float, exp_hz: float) -> dict[str, Any]:
        w = make_embodied_world(
            pack,
            wiring=wiring,
            seed=seed,
            backend=backend,
            foods=[],
            explore_drive_hz=exp_hz,
            control_mode="level2_vnc_tuned",
            vnc_synapse_scale=syn_s,
            vnc_proprio_gain_hz=prop_hz,
            vnc_mn_norm_hz=25.0,
            datasets_dir=datasets_dir,
        )
        alt_acc = 0.0
        mn_acc = 0.0
        for _ in range(ticks_per_eval):
            step_embodied_tick(w)
            alt_acc += w.last_vnc_tripod_alt
            mn_acc += w.vnc_mn_mean_hz
        mean_mn = mn_acc / ticks_per_eval
        mean_alt = alt_acc / ticks_per_eval
        # Objective rewards genuine planar travel + healthy physiological MN activity (5..80 Hz)
        # without seizure saturation (> 180 Hz).
        health = 1.0 if mean_mn <= 120.0 else max(0.1, 120.0 / mean_mn)
        score = (w.distance_traveled + 0.15 * mean_alt) * health
        return {
            "vnc_synapse_scale": syn_s,
            "vnc_proprio_gain_hz": prop_hz,
            "explore_drive_hz": exp_hz,
            "distance_cm": round(w.distance_traveled, 4),
            "vnc_mn_mean_hz": round(mean_mn, 3),
            "vnc_tripod_alternation": round(mean_alt, 4),
            "score": round(score, 4),
            "realtime_factor": w.timing.realtime_factor,
        }

    trials = [_eval("reference", s, p, e) for s, p, e in candidates]
    best = max(trials, key=lambda r: r["score"])
    baseline = trials[0]
    shuffled_at_best = _eval(
        "shuffled_control",
        best["vnc_synapse_scale"],
        best["vnc_proprio_gain_hz"],
        best["explore_drive_hz"],
    )
    return {
        "dataset_id": pack.dataset_id,
        "backend": backend,
        "seed": seed,
        "ticks_per_eval": ticks_per_eval,
        "wall_seconds": round(time.perf_counter() - t0, 3),
        "framing_note": EMBODIED_LEVEL2_TUNED_FRAMING,
        "baseline_untuned": baseline,
        "best_intact": best,
        "shuffled_at_best": shuffled_at_best,
        "all_trials": trials,
    }
