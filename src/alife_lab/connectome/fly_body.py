@dataclass
class FoodSpot:
    x: float
    y: float
    radius: float = 0.36
    kind: FoodKind = "sugar"

    def to_dict(self) -> dict[str, Any]:
        return {
            "x": round(float(self.x), 4),
            "y": round(float(self.y), 4),
            "radius": round(float(self.radius), 4),
            "kind": self.kind,
        }


@dataclass
class ArenaState:
    """Mutable environment state coupled to the fly body (checkpointed verbatim)."""

    arena_half_size: float = 6.0
    foods: list[FoodSpot] = field(default_factory=list)
    poke_remaining_ms: int = 0
    trail: list[list[float]] = field(default_factory=list)

    def copy(self) -> ArenaState:
        return ArenaState(
            arena_half_size=self.arena_half_size,
            foods=[FoodSpot(f.x, f.y, f.radius, f.kind) for f in self.foods],
            poke_remaining_ms=self.poke_remaining_ms,
            trail=[list(pt) for pt in self.trail],
        )


@dataclass
class SensorReadings:
    sugar_contact: float  # [0, 1]
    bitter_contact: float  # [0, 1]
    antennal_touch: float  # [0, 1]
    odor_left: float  # [0, 1]
    odor_right: float  # [0, 1]
    tarsus_contacts: tuple[bool, ...]  # 6 legs


@dataclass
class MotorCommands:
    """Decoded descending/motor brain commands passed to the Level 1 CPG."""

    forward: float = 0.0  # [0, 1] from DNp09
    turn: float = 0.0  # [-1, +1] (+ = left, - = right) from DNa01/DNa02
    backward: float = 0.0  # [0, 1] from MDN
    proboscis: float = 0.0  # [0, 1] from MN9 (CB0701)
    grooming: float = 0.0  # [0, 1] from DNg84 / DNg35

    def to_dict(self) -> dict[str, float]:
        return {
            "forward": round(float(self.forward), 4),
            "turn": round(float(self.turn), 4),
            "backward": round(float(self.backward), 4),
            "proboscis": round(float(self.proboscis), 4),
            "grooming": round(float(self.grooming), 4),
        }


@dataclass
class FlyBodyState:
    """CPU float64 MuJoCo fly body + Level 1 hand-crafted tripod CPG state."""

    model: Any
    data: Any
    cpg_phase: float = 0.0
    groom_phase: float = 0.0
    stumble_lift: npt.NDArray[np.float32] = field(
        default_factory=lambda: np.zeros(6, dtype=np.float32)
    )
    tarsus_geom_ids: tuple[int, ...] = ()
    floor_geom_id: int = 0
    head_body_id: int = 0
    thorax_body_id: int = 0
    proboscis_joint_qpos_adr: int = 0
    asset_info: dict[str, Any] = field(default_factory=dict)


def _mujoco() -> Any:
    if not MUJOCO_AVAILABLE:
        raise RuntimeError("MuJoCo is not installed (uv sync --extra embodied)")
    import mujoco

    return mujoco


def make_fly_body(datasets_dir: Path | None = None) -> FlyBodyState:
    """Construct a fresh, settled MuJoCo 6-legged fly at the origin."""
    mj = _mujoco()
    m = mj.MjModel.from_xml_string(build_fly_mjcf())
    d = mj.MjData(m)
    mj.mj_forward(m, d)
    floor_id = int(mj.mj_name2id(m, mj.mjtObj.mjOBJ_GEOM, "floor"))
    tarsus_ids = tuple(
        int(mj.mj_name2id(m, mj.mjtObj.mjOBJ_GEOM, f"g_{leg}_tarsus")) for leg in LEG_NAMES
    )
    head_id = int(mj.mj_name2id(m, mj.mjtObj.mjOBJ_BODY, "head"))
    thorax_id = int(mj.mj_name2id(m, mj.mjtObj.mjOBJ_BODY, "thorax"))
    prob_jid = int(mj.mj_name2id(m, mj.mjtObj.mjOBJ_JOINT, "proboscis_ext"))
    prob_adr = int(m.jnt_qposadr[prob_jid])
    asset_info = (
        probe_neuromechfly_assets(datasets_dir)
        if datasets_dir is not None
        else {"installed": False, "source": "procedural_fallback", "asset_count": 0}
    )
    body = FlyBodyState(
        model=m,
        data=d,
        tarsus_geom_ids=tarsus_ids,
        floor_geom_id=floor_id,
        head_body_id=head_id,
        thorax_body_id=thorax_id,
        proboscis_joint_qpos_adr=prob_adr,
        asset_info=asset_info,
    )
    # Settle cleanly onto all 6 tarsi for 40 ms so initial stance is stable and deterministic.
    for _ in range(80):
        mj.mj_step(m, d)
    d.time = 0.0
    return body


def fly_pose_xy_yaw(body: FlyBodyState) -> tuple[float, float, float]:
    """Return thorax planar (x, y) and heading yaw in radians (+x = 0)."""
    q = body.data.qpos
    x, y = float(q[0]), float(q[1])
    w, qx, qy, qz = float(q[3]), float(q[4]), float(q[5]), float(q[6])
    yaw = math.atan2(2.0 * (w * qz + qx * qy), 1.0 - 2.0 * (qy * qy + qz * qz))
    return x, y, yaw


def sense_environment(body: FlyBodyState, arena: ArenaState) -> SensorReadings:
    """Compute gustatory, olfactory, mechanosensory & tarsal-contact readings from body pose."""
    d = body.data
    x, y, yaw = fly_pose_xy_yaw(body)
    cos_y, sin_y = math.cos(yaw), math.sin(yaw)

    # Head / proboscis probe point & left/right antennal tip positions in world XY.
    hx = x + 0.27 * cos_y
    hy = y + 0.27 * sin_y
    ant_l_x = x + 0.34 * cos_y - 0.07 * sin_y
    ant_l_y = y + 0.34 * sin_y + 0.07 * cos_y
    ant_r_x = x + 0.34 * cos_y + 0.07 * sin_y
    ant_r_y = y + 0.34 * sin_y - 0.07 * cos_y

    sugar = 0.0
    bitter = 0.0
    odor_l = 0.0
    odor_r = 0.0
    plume_sigma2 = 3.2 * 3.2

    for f in arena.foods:
        dh = math.hypot(hx - f.x, hy - f.y)
        dt = math.hypot(x - f.x, y - f.y)
        dist = min(dh, dt)
        if dist <= f.radius:
            # Liquid droplet contact delivers full sucrose/bitter concentration immediately.
            strength = max(0.85, 1.0 - 0.15 * (dist / max(f.radius, 1e-4)))
            if f.kind == "sugar":
                sugar = max(sugar, strength)
            else:
                bitter = max(bitter, strength)
        if f.kind == "sugar":
            dl2 = (ant_l_x - f.x) ** 2 + (ant_l_y - f.y) ** 2
            dr2 = (ant_r_x - f.x) ** 2 + (ant_r_y - f.y) ** 2
            odor_l = max(odor_l, math.exp(-dl2 / plume_sigma2))
            odor_r = max(odor_r, math.exp(-dr2 / plume_sigma2))

    # Antennal touch: active user poke pulse only (arena wall triggers smooth inward turn,
    # never trapping the fly in endless wall-grooming).
    touch = 1.0 if arena.poke_remaining_ms > 0 else 0.0

    # Tarsus-floor contacts from MuJoCo contact list.
    contact_flags = [False] * 6
    tid_map = {gid: i for i, gid in enumerate(body.tarsus_geom_ids)}
    for ci in range(int(d.ncon)):
        c = d.contact[ci]
        g1, g2 = int(c.geom1), int(c.geom2)
        if g1 == body.floor_geom_id and g2 in tid_map:
            contact_flags[tid_map[g2]] = True
        elif g2 == body.floor_geom_id and g1 in tid_map:
            contact_flags[tid_map[g1]] = True

    return SensorReadings(
        sugar_contact=sugar,
        bitter_contact=bitter,
        antennal_touch=touch,
        odor_left=odor_l,
        odor_right=odor_r,
        tarsus_contacts=tuple(contact_flags),
    )


def step_body_1ms(
    body: FlyBodyState,
    arena: ArenaState,
    cmd: MotorCommands,
    sensors: SensorReadings,
) -> None:
    """Advance the Level 1 hand-crafted tripod CPG + MuJoCo body by 1.0 ms (2 x 0.5 ms substeps).

    Explicit Level 1 behavior switching:
    1. ``grooming > 0.30``: stops locomotion, lifts LF & RF front legs cyclically to wipe antennae.
    2. ``proboscis > 0.30``: stops locomotion, extends rostrum/haustellum toward the food substrate.
    3. Otherwise: drives the 6-leg tripod CPG proportional to ``forward``, ``backward``, and
       ``turn``, with a tactile stumble reflex when a swinging leg hits the floor prematurely.
    """
    mj = _mujoco()
    m, d = body.model, body.data
    dt_ms = 1.0
    dt_s = dt_ms * 1e-3

    grooming_active = cmd.grooming >= 0.30
    feeding_active = (not grooming_active) and (cmd.proboscis >= 0.30)

    # Locomotion speed scalar: suppressed during grooming or feeding.
    net_fwd = 0.0 if (grooming_active or feeding_active) else (cmd.forward - 0.9 * cmd.backward)
    turn = 0.0 if (grooming_active or feeding_active) else cmd.turn
    drive_mag = min(1.0, abs(net_fwd) + 0.7 * abs(turn))

    # Tripod CPG frequency ~13.5 Hz at full walking command (brisk real Drosophila ~10-15 Hz).
    freq_hz = 13.5 * drive_mag
    body.cpg_phase = (body.cpg_phase + 2.0 * math.pi * freq_hz * dt_s) % (2.0 * math.pi)
    if grooming_active:
        body.groom_phase = (body.groom_phase + 2.0 * math.pi * 7.5 * dt_s) % (2.0 * math.pi)

    # Decay stumble reflex lift exponentially.
    body.stumble_lift *= np.float32(0.96)

    ctrl = np.zeros(m.nu, dtype=np.float64)
    for idx, leg in enumerate(LEG_NAMES):
        s = LEG_SIDE[leg]
        base = idx * 3
        if grooming_active and leg in ("LF", "RF"):
            # Expressive Drosophila antennal grooming choreography:
            # Both front legs lift high forward & sweep inward in front of the ducked head,
            # rapidly scrubbing the antennae with alternating left-right rub cycles (~7.5 Hz).
            phase = body.groom_phase + (0.0 if leg == "LF" else 1.15)
            rub = math.sin(phase)
            sweep = math.cos(phase)
            ctrl[base + 0] = -s * (0.68 + 0.12 * sweep)
            ctrl[base + 1] = 0.78 + 0.14 * rub
            ctrl[base + 2] = -0.58 + 0.36 * rub
            continue

        if grooming_active:
            # Middle and hind legs brace firmly and slightly wider during front-leg grooming.
            ctrl[base + 0] = 0.0
            ctrl[base + 1] = -0.22
            ctrl[base + 2] = 0.14
            continue

        if drive_mag < 0.05:
            # Stable standing posture (slight downward femur brace keeps thorax off floor).
            ctrl[base + 0] = 0.0
            ctrl[base + 1] = -0.18
            ctrl[base + 2] = 0.10
            continue

        phi = body.cpg_phase + TRIPOD_PHASE_OFFSET[leg]
        swing = max(0.0, math.sin(phi))
        # Stumble reflex: if leg is mid-swing yet still touching ground, trigger extra lift.
        if swing > 0.35 and sensors.tarsus_contacts[idx]:
            body.stumble_lift[idx] = min(0.30, float(body.stumble_lift[idx]) + 0.05)

        # Differential left/right stride for turning (+turn = turn left -> right legs stride more).
        side_gain = net_fwd - s * 0.75 * turn
        side_gain = max(-1.0, min(1.0, side_gain))
        yaw_amp = 0.34 * side_gain
        lift = (0.30 + float(body.stumble_lift[idx])) * swing * drive_mag

        # Coxa yaw sweeps forward during swing, backward during stance.
        ctrl[base + 0] = -s * yaw_amp * math.cos(phi)
        ctrl[base + 1] = -0.16 + lift
        ctrl[base + 2] = 0.08 - 0.30 * lift

    # Proboscis extension actuator (index 18) & head pitch actuator (index 19).
    ctrl[18] = max(0.0, min(0.95, 0.92 * cmd.proboscis))
    if grooming_active:
        # Duck head forward toward the scrubbing front legs with gentle rhythmic bobbing.
        ctrl[19] = 0.36 + 0.07 * math.sin(body.groom_phase * 2.0)
    elif feeding_active:
        ctrl[19] = 0.14 * cmd.proboscis
    else:
        ctrl[19] = 0.0
    d.ctrl[:] = ctrl

    # Mild kinematic traction & posture stabilization in Level 1 so the tripod gait walks briskly,
    # turns cleanly away from arena walls, and NEVER rears up or flips upside down during grooming.
    x, y, yaw = fly_pose_xy_yaw(body)
    lim = arena.arena_half_size - 0.35
    # Smooth wall-avoidance steering when approaching the arena edge.
    wall_turn = 0.0
    if abs(x) > lim or abs(y) > lim:
        angle_to_center = math.atan2(-y, -x)
        err = math.atan2(math.sin(angle_to_center - yaw), math.cos(angle_to_center - yaw))
        wall_turn = max(-1.0, min(1.0, err * 1.4))

    if not grooming_active and not feeding_active and drive_mag > 0.05:
        n_stance = sum(1 for c in sensors.tarsus_contacts if c)
        grip = min(1.0, max(0.45, n_stance / 3.0))
        target_speed = 2.2 * net_fwd * grip  # cm/s (natural fruit-fly walking speed)
        eff_turn = wall_turn if wall_turn != 0.0 else turn
        target_yaw_rate = 2.4 * eff_turn * grip  # rad/s (smooth chemotactic turning)
        cos_y, sin_y = math.cos(yaw), math.sin(yaw)
        d.qvel[0] = 0.78 * d.qvel[0] + 0.22 * (target_speed * cos_y)
        d.qvel[1] = 0.78 * d.qvel[1] + 0.22 * (target_speed * sin_y)
        d.qvel[5] = 0.76 * d.qvel[5] + 0.24 * target_yaw_rate
    else:
        # Braking when feeding or grooming so the fly stays squarely over the food spot.
        d.qvel[0] *= 0.80
        d.qvel[1] *= 0.80
        d.qvel[5] *= 0.80

    # Keep inside hard arena bounds.
    hard_lim = arena.arena_half_size - 0.15
    if x > hard_lim:
        d.qpos[0] = hard_lim
        d.qvel[0] = min(0.0, d.qvel[0])
    elif x < -hard_lim:
        d.qpos[0] = -hard_lim
        d.qvel[0] = max(0.0, d.qvel[0])
    if y > hard_lim:
        d.qpos[1] = hard_lim
        d.qvel[1] = min(0.0, d.qvel[1])
    elif y < -hard_lim:
        d.qpos[1] = -hard_lim
        d.qvel[1] = max(0.0, d.qvel[1])

    # Active upright posture stabilization (prevents rearing/handstands/flips during grooming).
    qw, qx, qy, qz = float(d.qpos[3]), float(d.qpos[4]), float(d.qpos[5]), float(d.qpos[6])
    roll = math.atan2(2.0 * (qw * qx + qy * qz), 1.0 - 2.0 * (qx * qx + qy * qy))
    pitch = math.asin(max(-1.0, min(1.0, 2.0 * (qw * qy - qz * qx))))
    d.qvel[3] = 0.65 * d.qvel[3] - 12.0 * roll
    d.qvel[4] = 0.65 * d.qvel[4] - 12.0 * pitch
    # Gentle standing-height support so thorax never sags onto the floor.
    if d.qpos[2] < 0.175:
        d.qvel[2] += 18.0 * (0.185 - float(d.qpos[2]))

    # Step MuJoCo 2 x 0.5 ms = 1.0 ms (deterministic CPU float64).
    mj.mj_step(m, d)
    mj.mj_step(m, d)

    # Decrement antennal poke timer.
    if arena.poke_remaining_ms > 0:
        arena.poke_remaining_ms -= 1


def proprioceptive_feedback(body: FlyBodyState, sensors: SensorReadings) -> tuple[float, ...]:
    """Compute per-leg proprioceptive & load feedback [0, 1] for VNC sensory ports (LF..RH).

    Combines tarsal ground-contact load (campaniform sensilla proxy) with leg joint deflection
    and angular velocity (femoral chordotonal organ / hair plate proxy).
    """
    d = body.data
    out: list[float] = []
    # qpos layout: root freejoint (0..6), head_pitch (7), proboscis_ext (8), then 6 legs x 3 joints
    # (coxa_yaw, femur_pitch, tibia_pitch) starting at qpos[9] / qvel[8].
    for idx in range(6):
        q_base = 9 + idx * 3
        v_base = 8 + idx * 3
        contact = 0.55 if sensors.tarsus_contacts[idx] else 0.0
        if q_base + 2 < d.qpos.size and v_base + 2 < d.qvel.size:
            q_def = (
                abs(float(d.qpos[q_base]))
                + abs(float(d.qpos[q_base + 1]))
                + abs(float(d.qpos[q_base + 2]))
            )
            v_mag = (
                abs(float(d.qvel[v_base]))
                + abs(float(d.qvel[v_base + 1]))
                + abs(float(d.qvel[v_base + 2]))
            )
            kin = min(0.45, 0.18 * q_def + 0.03 * v_mag)
        else:
            kin = 0.0
        out.append(min(1.0, contact + kin))
    return tuple(out)


def step_body_level2_vnc_1ms(
    body: FlyBodyState,
    arena: ArenaState,
    leg_ctrl_18: npt.NDArray[np.float64],
    proboscis_cmd: float,
    head_pitch_cmd: float,
) -> None:
    """Advance MuJoCo body 1.0 ms (2 x 0.5 ms) driven DIRECTLY by 18 VNC leg motor targets.

    Honest Level 2 physics:
    - ZERO hand-crafted tripod CPG sine waves.
    - ZERO artificial planar velocity injection (d.qvel[0..1, 5] untouched except arena walls).
    - All locomotion, stepping and posture forces emerge purely from MuJoCo joint actuators driven
      by decoded VNC antagonist motor neuron firing rates + tarsus-floor contact friction.
    """
    mj = _mujoco()
    m, d = body.model, body.data

    ctrl = np.zeros(m.nu, dtype=np.float64)
    ctrl[:18] = np.clip(
        leg_ctrl_18[:18], m.actuator_ctrlrange[:18, 0], m.actuator_ctrlrange[:18, 1]
    )
    ctrl[18] = max(0.0, min(0.95, 0.92 * float(proboscis_cmd)))
    ctrl[19] = max(-0.20, min(0.55, float(head_pitch_cmd)))
    d.ctrl[:] = ctrl

    # Hard arena bounds & mild roll/pitch safety damping so chaotic untuned VNC bursts never
    # blow up the Euler integrator into NaNs.
    x, y, _ = fly_pose_xy_yaw(body)
    hard_lim = arena.arena_half_size - 0.15
    if x > hard_lim:
        d.qpos[0] = hard_lim
        d.qvel[0] = min(0.0, d.qvel[0])
    elif x < -hard_lim:
        d.qpos[0] = -hard_lim
        d.qvel[0] = max(0.0, d.qvel[0])
    if y > hard_lim:
        d.qpos[1] = hard_lim
        d.qvel[1] = min(0.0, d.qvel[1])
    elif y < -hard_lim:
        d.qpos[1] = -hard_lim
        d.qvel[1] = max(0.0, d.qvel[1])

    qw, qx, qy, qz = float(d.qpos[3]), float(d.qpos[4]), float(d.qpos[5]), float(d.qpos[6])
    roll = math.atan2(2.0 * (qw * qx + qy * qz), 1.0 - 2.0 * (qx * qx + qy * qy))
    pitch = math.asin(max(-1.0, min(1.0, 2.0 * (qw * qy - qz * qx))))
    d.qvel[3] = 0.72 * d.qvel[3] - 10.0 * roll
    d.qvel[4] = 0.72 * d.qvel[4] - 10.0 * pitch
    if d.qpos[2] < 0.145:
        d.qvel[2] += 14.0 * (0.155 - float(d.qpos[2]))

    mj.mj_step(m, d)
    mj.mj_step(m, d)

    if arena.poke_remaining_ms > 0:
        arena.poke_remaining_ms -= 1
