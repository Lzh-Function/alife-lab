"""Phase F8 Level 1: MuJoCo 6-legged Drosophila body, Level 1 tripod CPG & arena environment.

Honest Level 1 framing:
- Leg oscillation rhythms and the stumble reflex are **hand-crafted** (inspired by NeuroMechFly v2,
  Wang-Chen et al. 2024), NOT generated by a biological VNC connectome (Phase F8 Level 2).
- Descending / motor commands from the spiking connectome brain (``forward``, ``turn``,
  ``backward``, ``proboscis``, ``grooming``) switch and modulate these motor programs in real time,
  sensors (taste, bilateral olfaction, antennal touch) close the loop back into brain sensory ports.
- Contact dynamics use fast capsule primitives in CPU float64 MuJoCo 3 for deterministic replay;
  when the Apache-2.0 NeuroMechFly v2 body asset pack is installed under
  ``.alife/datasets/neuromechfly_v2/``, its manifest & anatomical proportions are verified and
  recorded in provenance without importing any FlyGym Python code.
"""

